## Frase, oração e período
Frase é um enunciado que comunica uma ideia em determinada situação. Pode ter verbo (“A aula começou”) ou não (“Que notícia boa!”). Oração é a estrutura organizada em torno de um verbo ou locução verbal. Período é o enunciado formado por uma ou mais orações.

Período simples tem uma oração: “A turma estudou”. Período composto tem duas ou mais: “A turma estudou e realizou a atividade”.

## Sujeito e predicado
Sujeito é o termo sobre o qual se declara algo. Predicado é aquilo que se declara sobre o sujeito. Em “Os estudantes revisaram a matéria”, “Os estudantes” é o sujeito e “revisaram a matéria” é o predicado.

O sujeito pode ser simples (“A professora explicou”), composto (“Ana e Pedro chegaram”), oculto ou desinencial (identificado pela forma verbal: “Estudamos bastante”) e indeterminado. Há também oração sem sujeito, como em “Choveu ontem” e “Faz dois anos”.

## Pontuação essencial
Ponto final encerra uma declaração. Ponto de interrogação marca pergunta direta. Ponto de exclamação expressa emoção, surpresa ou ênfase. Dois-pontos anunciam explicação, enumeração ou fala. Ponto e vírgula separa partes de um período quando a pausa é maior que a da vírgula e menor que a do ponto.

A vírgula pode separar itens de uma enumeração, isolar vocativo, marcar aposto explicativo e separar certas orações ou termos deslocados. Exemplos: “Comprei lápis, cadernos e livros”; “Maria, venha aqui”; “Machado de Assis, grande escritor brasileiro, nasceu no Rio de Janeiro”.

## Cuidado com a vírgula
Não separe sujeito e verbo por vírgula: “Os alunos, estudaram” está incorreto na construção comum. A forma adequada é “Os alunos estudaram”. Também não separe o verbo de seu complemento sem motivo sintático.

A vírgula pode mudar a interpretação: “Vamos comer, crianças” chama as crianças; “Vamos comer crianças” produz outro sentido. A pontuação organiza a estrutura e evita ambiguidades.

## Conectivos e clareza
Conjunções estabelecem relações de sentido. “E” soma ideias; “mas” e “porém” indicam oposição; “porque” pode introduzir causa ou explicação; “portanto” indica conclusão; “embora” introduz concessão. Escolha o conectivo de acordo com a relação lógica pretendida.

## Pratique
