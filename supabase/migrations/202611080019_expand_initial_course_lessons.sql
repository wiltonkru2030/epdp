## O que é a língua portuguesa?
A língua é um sistema organizado de palavras, sons e regras que permite a comunicação. Usamos a língua para informar, perguntar, argumentar, contar histórias, expressar sentimentos e construir relações. Aprender português não é apenas decorar regras: é compreender como as escolhas de linguagem produzem sentido em cada situação.

A língua apresenta variedades regionais, sociais e históricas. A fala cotidiana pode ser diferente da escrita formal. Em situações profissionais, acadêmicas e em concursos, é importante conhecer a norma-padrão e saber quando utilizá-la, sem tratar as demais variedades como inferiores.

## Letras, fonemas e dígrafos
Letra é o sinal gráfico que escrevemos. Fonema é a unidade sonora capaz de distinguir palavras. A relação entre letras e sons nem sempre é de um para um.

Exemplos: em “faca”, quatro letras representam quatro fonemas; em “chave”, as letras “ch” representam um único fonema; em “carro”, “rr” representa um único fonema; a letra “x” pode representar sons diferentes, como em “exame” e “táxi”.

Dígrafo é o encontro de duas letras que representam um único fonema. Exemplos: ch, lh, nh, rr, ss, qu (em “quilo”) e gu (em “guerra”), conforme a pronúncia.

## Sílabas e tonicidade
Sílaba é cada grupo sonoro pronunciado em um impulso de voz. “Ca-sa” tem duas sílabas; “es-co-la” tem três; “flor” tem uma.

A sílaba tônica é pronunciada com maior intensidade. Conforme a posição dessa sílaba, a palavra pode ser oxítona (última sílaba: café), paroxítona (penúltima: fácil) ou proparoxítona (antepenúltima: lâmpada).

Não confunda número de sílabas com posição da sílaba tônica: são classificações diferentes.

## Classes de palavras
As palavras são classificadas de acordo com suas características e funções. Substantivo nomeia: estudante, cidade, coragem. Adjetivo caracteriza: atento, brasileiro, difícil. Verbo expressa ação, estado ou fenômeno: estudar, permanecer, chover.

Artigo acompanha o substantivo: o, a, um, uma. Pronome acompanha ou substitui um nome: meu, ela, aquele. Numeral indica quantidade ou ordem: três, primeiro. Advérbio modifica verbo, adjetivo ou outro advérbio: ontem, muito, cuidadosamente.

Preposição relaciona termos: de, com, para. Conjunção conecta orações ou termos: e, mas, porque. Interjeição expressa reação: ufa!, atenção!

Uma palavra pode mudar de classe conforme o contexto. Em “o jantar estava pronto”, “jantar” é substantivo; em “vamos jantar”, é verbo.

## Atenção: erros comuns
Letra não é a mesma coisa que fonema. Nem toda sílaba escrita corresponde a uma letra. A classificação tônica depende da pronúncia, não do tamanho da palavra. Para identificar a classe gramatical, observe a função que a palavra exerce na frase.

