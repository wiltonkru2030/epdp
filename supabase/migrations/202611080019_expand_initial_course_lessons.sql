## Ler é construir sentidos
Interpretar é compreender o que o texto comunica e justificar conclusões com pistas presentes nele. Uma boa interpretação não inventa informações nem depende apenas da opinião pessoal. Toda resposta deve ser sustentada por palavras, relações ou ideias do texto.

## Tema e ideia principal
Tema é o assunto geral. Ideia principal é a afirmação central desenvolvida pelo texto sobre esse assunto. Um texto pode falar sobre educação (tema) e defender que a leitura diária amplia o vocabulário (ideia principal).

Detalhes, exemplos, dados e explicações ajudam a desenvolver a ideia principal, mas nem sempre são o foco central.

## Informação explícita e inferência
Informação explícita aparece diretamente no texto. Inferência é uma conclusão construída a partir de pistas. Se o texto diz “Joana saiu com guarda-chuva e voltou com os sapatos molhados”, podemos inferir que provavelmente choveu, mas não afirmar onde ela esteve se isso não foi informado.

A inferência precisa ser plausível e coerente com o conjunto do texto. Evite extrapolar uma informação isolada.

## Coesão e referência
Pronomes e expressões retomam termos anteriores. Em “Marina comprou um livro. Ela começou a leitura à noite”, “ela” retoma Marina. Conectivos indicam relações: causa, consequência, oposição, condição, conclusão e tempo.

Observe palavras como “porém”, “portanto”, “porque”, “embora”, “quando” e “se”. Elas ajudam a identificar a organização lógica das ideias.

## Objetivo, gênero e ponto de vista
Pergunte quem produziu o texto, para quem, com qual finalidade e em qual gênero. Uma notícia tende a informar acontecimentos; um anúncio busca persuadir; um artigo de opinião defende um ponto de vista; uma crônica pode narrar situações cotidianas com reflexão ou humor.

Diferencie fato verificável de opinião. Expressões como “na minha avaliação”, “é fundamental” e “deveria” podem sinalizar posicionamento, mas o contexto é decisivo.

## Estratégia de leitura
1. Leia o texto inteiro antes de responder.
2. Identifique o tema e a finalidade.
3. Marque palavras-chave e conectivos.
4. Localize a frase que sustenta a resposta.
5. Elimine alternativas que contradizem o texto ou acrescentam informações não apresentadas.
6. Revise se sua conclusão respeita o contexto completo.

## Pratique
