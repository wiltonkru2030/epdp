## O que é ortografia?
Ortografia é o conjunto de convenções que determina a forma correta de escrever as palavras. A pronúncia pode variar entre regiões, mas a escrita segue uma norma comum. Ler, consultar dicionários e observar famílias de palavras são estratégias úteis para fixar a grafia.

## S, SS, C, Ç e X
Entre vogais, o “ss” costuma representar o som /s/: passeio, assunto, possível. Um único “s” entre vogais geralmente tem som de /z/: casa, mesa, aviso. O “ç” aparece antes de a, o e u: praça, almoço, açúcar; não se usa ç antes de e ou i.

O “c” antes de e e i pode representar o som /s/: cidade, cedo. O “c” antes de a, o e u normalmente representa /k/: casa, coisa, cultura. O “x” pode ter diferentes sons: xícara, exame, táxi, próximo. Por isso, nem toda dúvida ortográfica se resolve apenas pelo som.

## G e J
O “g” antes de e e i pode ter som semelhante ao de j: gelo, girafa. O “j” aparece em palavras como janela, jeito e jiló. Em muitos casos, a grafia depende da origem da palavra e deve ser memorizada por meio da leitura e da consulta.

## Sílaba tônica e acentuação
Oxítonas têm a última sílaba tônica. São acentuadas, entre outros casos, as terminadas em a(s), e(s), o(s), em(ens): sofá, café, cipó, também, parabéns.

Paroxítonas têm a penúltima sílaba tônica. Recebem acento em terminações previstas pela regra, como l, n, r, x, ps, ã(s), ão(s), um(uns), i(s), us e ditongo: fácil, hífen, caráter, tórax, bíceps, órfã, órgão, álbum, júri, vírus, história.

Proparoxítonas têm a antepenúltima sílaba tônica e todas são acentuadas: lâmpada, médico, público, matemática.

## Hiato e acentos diferenciais
O “i” e o “u” tônicos em hiato podem receber acento quando formam sílaba sozinhos ou acompanhados de “s”, observadas as condições da regra: saída, país, baú. Há exceções, por isso consulte a regra completa quando houver dúvida.

Alguns acentos diferenciais permanecem para distinguir formas: “pôde” (passado) e “pode” (presente); “pôr” (verbo) e “por” (preposição); “têm” (plural) e “tem” (singular).

## Atenção: método para acentuar
Primeiro, pronuncie a palavra e identifique a sílaba tônica. Depois, classifique-a como oxítona, paroxítona ou proparoxítona. Por fim, observe a terminação e aplique a regra correspondente. Não escolha o acento apenas porque a palavra parece “forte”.

